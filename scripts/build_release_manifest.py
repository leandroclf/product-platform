#!/usr/bin/env python3
"""Create a non-attested, reviewable source-to-artifact manifest for harness releases."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re

TAG = re.compile(r"^harness-v[0-9]+\.[0-9]+\.[0-9]+$")
SHA = re.compile(r"^[0-9a-f]{40}$")


def make_manifest(directory, *, tag, source_sha, repository, generated_at=None):
    root = Path(directory)
    if not TAG.fullmatch(tag) or not SHA.fullmatch(source_sha):
        raise ValueError("Malformed release tag or source commit")
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository):
        raise ValueError("Invalid source repository")
    files = sorted([*root.glob("*.tgz"), *root.glob("*.whl")])
    if len(files) < 2 or len({p.name for p in files}) != len(files):
        raise ValueError("Expected both npm tarball and Python wheel artifacts")
    artifacts = []
    for file in files:
        if file.is_symlink() or not file.is_file() or file.stat().st_size <= 0:
            raise ValueError("Invalid artifact")
        digest = hashlib.sha256(file.read_bytes()).hexdigest()
        artifacts.append({"filename": file.name, "bytes": file.stat().st_size, "sha256": digest})
    return {
        "schema_version": 1, "provenance_level": "self-reported-not-attested",
        "repository": repository, "source_commit": source_sha, "tag": tag,
        "generated_at": generated_at or datetime.now(timezone.utc).isoformat(),
        "artifacts": artifacts,
        "limitations": "Manifest is generated by the release job; it is not a cryptographic build attestation or SLSA certification.",
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--directory", required=True, type=Path)
    parser.add_argument("--tag", required=True)
    parser.add_argument("--sha", required=True)
    parser.add_argument("--repository", required=True)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    report = make_manifest(args.directory, tag=args.tag, source_sha=args.sha, repository=args.repository)
    args.output.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
